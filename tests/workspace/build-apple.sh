#!/usr/bin/env bash
# Build this checkout's Linux package in a disposable Apple container. Transfer
# sources and outputs through Nix; no host mounts or existing credentials.
set -euo pipefail
cd "$(dirname "$0")/../.."
attribute=${1:-packages.aarch64-linux.shikigami-runtime}
[[ "$attribute" =~ ^packages\.aarch64-linux\.[a-zA-Z0-9._-]+$ ]] || { echo 'Expected a packages.aarch64-linux.<package> attribute' >&2; exit 64; }
taskdir=$(mktemp -d /tmp/shikigami-workspace-build.XXXXXX)
name="shikigami-workspace-build-$(date -u +%Y%m%d%H%M%S)-$$"
port=$(python3 - <<'PY'
import socket
with socket.socket() as listener:
    listener.bind(('127.0.0.1',0))
    print(listener.getsockname()[1])
PY
)
created=false
cleanup() {
  result=$?
  if "$created"; then
    container stop --time 5 "$name" >/dev/null || { if [[ $result == 0 ]]; then result=1; fi; }
  fi
  # Only credentials generated by this invocation, inside its fresh directory.
  rm -f "$taskdir/key" "$taskdir/key.pub" "$taskdir/known_hosts"
  exit "$result"
}
trap cleanup EXIT
printf '%s\n' "$name" > "$taskdir/container"
ssh-keygen -q -t ed25519 -N '' -f "$taskdir/key"
image='docker.io/kindest/node@sha256:ce977ae6d65918d0b58a5f8b5e940429c2ce42fa3a5619ec2bbc60b949c0ac95'
container run --rm --detach --name "$name" --cpus 8 --memory 16G --cap-add ALL -p "127.0.0.1:$port:22" "$image" /sbin/init >/dev/null
created=true
container exec --interactive "$name" /usr/bin/timeout 300 /bin/bash -s <<'GUEST'
set -euo pipefail
export DEBIAN_FRONTEND=noninteractive
apt-get update -qq
apt-get install -y --no-install-recommends nix-bin openssh-server ca-certificates >/dev/null 2>&1
install -d -m 700 /root/.ssh
install -d -m 755 /etc/nix
getent group nixbld >/dev/null || groupadd --system nixbld
for index in {1..8}; do
  useradd --system --gid nixbld --groups nixbld --home-dir /var/empty --no-create-home --shell /usr/sbin/nologin "nixbld-task$index"
done
cat >/etc/nix/nix.conf <<'NIX'
experimental-features = nix-command flakes
build-users-group = nixbld
max-jobs = 8
cores = 8
sandbox = true
NIX
cat >/etc/ssh/sshd_config.d/99-workspace-task.conf <<'SSH'
PasswordAuthentication no
KbdInteractiveAuthentication no
PermitRootLogin prohibit-password
AllowUsers root
SSH
systemctl daemon-reload
systemctl start ssh
nix --version
GUEST
container exec --interactive "$name" /bin/sh -c 'cat > /root/.ssh/authorized_keys && chmod 600 /root/.ssh/authorized_keys' < "$taskdir/key.pub"
hostkey=$(container exec "$name" cat /etc/ssh/ssh_host_ed25519_key.pub)
printf '[127.0.0.1]:%s %s\n' "$port" "$hostkey" > "$taskdir/known_hosts"
export NIX_SSHOPTS="-F /dev/null -o BatchMode=yes -o StrictHostKeyChecking=yes -o UserKnownHostsFile=$taskdir/known_hosts"
target="ssh-ng://root@127.0.0.1:$port?ssh-key=$taskdir/key"
nix store info --store "$target"
# Two cores avoid repeating the observed eight-job configure stall (FRIC-21).
# The cause is unknown; this is a bounded build recipe, not a package patch.
nix build --cores 2 --option timeout 3600 --option max-silent-time 600 --print-build-logs \
  --store "$target" ".#$attribute" --no-link --no-write-lock-file --json > "$taskdir/result.json"
runtime=$(python3 - "$taskdir/result.json" <<'PY'
import json,sys
result=json.load(open(sys.argv[1]))
assert len(result)==1
print(result[0]['outputs']['out'])
PY
)
# Trust only this task's output on the peer-verified, newly provisioned builder.
# Do not change the host's signature policy or trusted-key configuration.
nix copy --no-check-sigs --from "$target" "$runtime"
printf 'PASS Apple Linux build: %s; retained Nix result: %s/result.json\n' "$attribute" "$taskdir"
