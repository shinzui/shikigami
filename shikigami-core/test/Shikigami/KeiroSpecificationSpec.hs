-- | The checked specification is wired up, and the generated layer is generated.
--
-- @domain\/shikigami.keiro-workspace@ is the source of truth for Shikigami's
-- durable workflow identities, and @keiro-dsl@ enforces almost everything about
-- it — but only when someone runs it. These cases run in the ordinary suite and
-- cover the failures a @keiro-dsl@ invocation cannot catch at all, plus one it
-- catches only on the next scaffold:
--
--   1. A @.keiro@ file that exists in @domain\/@ but is not listed in the
--      manifest. Nothing composes it, nothing checks it, and nothing generates
--      from it — @check@, @inspect@, and @scaffold@ all see the manifest's
--      member set, so none of them can notice a file outside it.
--   2. A generated module that nobody pasted into @shikigami-core.cabal@. It
--      sits in @src@ uncompiled, so an error in it is invisible.
--   3. A @.cabal@ entry naming a generated module that no longer exists.
--   4. A generated file whose @-- \@generated@ banner was removed. @scaffold@
--      refuses to overwrite such a file, but only when scaffold next runs; here
--      it fails immediately.
--
-- Everything else — cross-node references, the language floor, warnings, and
-- evolution compatibility — belongs to @just keiro-gate@, which is the real
-- gate and which runs the toolchain.
--
-- The files are read as text rather than through a parser, exactly as
-- "Shikigami.PackageArchitectureSpec" does, so this suite does not acquire a
-- dependency on the toolchain it is checking.
module Shikigami.KeiroSpecificationSpec (tests) where

import Control.Monad (forM, when)
import Data.List (isSuffixOf, sort)
import Data.Maybe (mapMaybe)
import Data.Text (Text)
import Data.Text qualified as Text
import Data.Text.IO qualified as TIO
import System.Directory (doesDirectoryExist, doesFileExist, listDirectory, pathIsSymbolicLink)
import System.FilePath ((</>))
import Test.Tasty (TestTree, testGroup)
import Test.Tasty.HUnit (assertFailure, testCase, (@?=))

-- | The banner every generated module must carry verbatim.
generatedBanner :: Text
generatedBanner = "-- @generated by keiro-dsl"

manifestPath :: FilePath
manifestPath = "domain" </> "shikigami.keiro-workspace"

tests :: TestTree
tests =
  testGroup
    "keiro specification"
    [ testCase "the manifest lists exactly the .keiro files in domain/" do
        root <- repositoryRoot
        listed <- manifestMembers root
        onDisk <- domainMembers root
        sort listed @?= sort onDisk,
      testCase "the manifest declares the service, runtime package, and layout" do
        root <- repositoryRoot
        clauses <- manifestClauses root
        lookup "service" clauses @?= Just "shikigami"
        lookup "runtime-package" clauses @?= Just "shikigami-core"
        lookup "layout" clauses @?= Just "collocated",
      -- `context shikigami` already supplies `Shikigami` as the module root. A
      -- `module Shikigami` clause is a *prefix* applied on top of it, so it
      -- would scaffold Shikigami.Shikigami.*; see the Decision Log of
      -- 2026-08-19 in
      -- docs/plans/39-adopt-a-checked-keiro-dsl-specification-and-evolution-gate.md.
      testCase "the manifest declares no module prefix" do
        root <- repositoryRoot
        clauses <- manifestClauses root
        lookup "module" clauses @?= Nothing,
      testCase "every member declares language 6 and context shikigami" do
        root <- repositoryRoot
        members <- domainMembers root
        assertNonEmpty "workspace member" members
        results <- forM members \member -> do
          significant <- significantLines (root </> "domain" </> Text.unpack member)
          pure (member, take 2 significant)
        mapM_
          ( \(member, preamble) ->
              if preamble == ["language keiro-dsl 6", "context shikigami"]
                then pure ()
                else
                  assertFailure
                    ( Text.unpack member
                        <> " must begin with `language keiro-dsl 6` then `context shikigami`; found "
                        <> show preamble
                    )
          )
          results,
      testCase "every generated module carries the banner" do
        root <- repositoryRoot
        paths <- generatedModulePaths root
        assertNonEmpty "generated modules" paths
        mapM_
          ( \path -> do
              contents <- TIO.readFile (root </> path)
              let bannered = any (generatedBanner `Text.isPrefixOf`) (Text.lines contents)
              if bannered
                then pure ()
                else assertFailure (path <> " has lost its \"" <> Text.unpack generatedBanner <> "\" banner")
          )
          paths,
      -- A generated module that is not in the .cabal file is not compiled, and a
      -- .cabal entry with no file breaks the build for everyone else. Both
      -- directions are checked from one comparison.
      testCase "the .cabal module list matches the generated modules on disk" do
        root <- repositoryRoot
        paths <- generatedModulePaths root
        let onDisk = sort (map (moduleNameOf "shikigami-core/src/") paths)
        declared <- sort . filter isGeneratedModuleName <$> cabalModules root
        declared @?= onDisk
    ]

-- ── Reading the manifest ────────────────────────────────────────────────────

-- | The `spec` lines of the workspace manifest, in the order written.
manifestMembers :: FilePath -> IO [Text]
manifestMembers root = do
  contents <- TIO.readFile (root </> manifestPath)
  pure (mapMaybe specLine (Text.lines contents))
  where
    specLine line = case Text.words (Text.strip line) of
      ["spec", path] -> Just path
      _ -> Nothing

-- | Every non-`spec` clause of the manifest as a (keyword, value) pair.
manifestClauses :: FilePath -> IO [(Text, Text)]
manifestClauses root = do
  contents <- TIO.readFile (root </> manifestPath)
  pure (mapMaybe clause (Text.lines contents))
  where
    clause line = case Text.words (Text.strip line) of
      [keyword, value] | keyword /= "spec" -> Just (keyword, value)
      _ -> Nothing

-- | Every `.keiro` member under domain, relative to the manifest directory.
domainMembers :: FilePath -> IO [Text]
domainMembers root = walk ""
  where
    walk relative = do
      entries <- listDirectory (root </> "domain" </> relative)
      fmap concat $ forM entries \entry -> do
        let member = relative </> entry
            path = root </> "domain" </> member
        symbolic <- pathIsSymbolicLink path
        when symbolic (assertFailure "domain members must not be symbolic links")
        directory <- doesDirectoryExist path
        if directory
          then walk member
          else pure [Text.pack member | ".keiro" `isSuffixOf` member]

-- | A source's lines with comments and blanks removed, so the preamble can be
-- asserted without pinning the comment block above it.
significantLines :: FilePath -> IO [Text]
significantLines path = do
  contents <- TIO.readFile path
  pure
    [ stripped
    | line <- Text.lines contents,
      let stripped = Text.strip line,
      not (Text.null stripped),
      not ("#" `Text.isPrefixOf` stripped)
    ]

-- ── Reading the generated layer ─────────────────────────────────────────────

-- | Every Haskell file under a `Generated` directory in shikigami-core's source
-- tree, as a repository-relative path.
generatedModulePaths :: FilePath -> IO [FilePath]
generatedModulePaths root = do
  found <- walk (root </> "shikigami-core" </> "src")
  pure (sort [drop (length root + 1) path | path <- found, isGeneratedPath path])
  where
    isGeneratedPath path =
      ".hs" `isSuffixOf` path && ("/Generated/" `isInfix` path)

    isInfix needle haystack = Text.isInfixOf (Text.pack needle) (Text.pack haystack)

    walk dir = do
      entries <- listDirectory dir
      fmap concat . mapM (descend dir) $ entries

    -- Immutable edition-migration backups are recovery artifacts, not modules
    -- in the compiled source tree. Keep checking every live generated module.
    descend _ ".keiro-dsl-generated-haskell-migrations" = pure []
    descend dir entry = do
      let path = dir </> entry
      isDir <- doesDirectoryExist path
      if isDir then walk path else pure [path]

-- | The Haskell module name a source path under the given prefix compiles to.
moduleNameOf :: String -> FilePath -> Text
moduleNameOf prefix path =
  Text.replace "/" "."
    . Text.dropEnd (Text.length ".hs")
    . Text.pack
    $ drop (length prefix) path

-- | Every module named by shikigami-core's library stanza, exposed or not.
--
-- The stanza is machine-formatted by treefmt, so module names are the indented
-- single-word lines between a `*-modules:` keyword and the next keyword.
cabalModules :: FilePath -> IO [Text]
cabalModules root = do
  contents <- TIO.readFile (root </> "shikigami-core" </> "shikigami-core.cabal")
  pure (collect False (Text.lines contents))
  where
    collect _ [] = []
    collect inside (line : rest)
      | isModuleHeader line = collect True rest
      | not inside = collect False rest
      | otherwise = case Text.words line of
          [word] | isModuleName word -> word : collect True rest
          _ -> collect False rest

    isModuleHeader line =
      let stripped = Text.strip line
       in "exposed-modules:" `Text.isPrefixOf` stripped || "other-modules:" `Text.isPrefixOf` stripped

    isModuleName word = case Text.uncons word of
      Just (c, _) -> c `elem` ['A' .. 'Z']
      Nothing -> False

-- | Whether a module name belongs to the keiro-dsl generated layer.
isGeneratedModuleName :: Text -> Bool
isGeneratedModuleName name =
  "Shikigami.Generated." `Text.isPrefixOf` name || ".Generated." `Text.isInfixOf` name

-- ── Helpers ─────────────────────────────────────────────────────────────────

assertNonEmpty :: String -> [a] -> IO ()
assertNonEmpty label xs
  | null xs = assertFailure ("expected at least one " <> label <> "; found none, so this suite would pass vacuously")
  | otherwise = pure ()

-- | Find the repository root from wherever the test runner started, exactly as
-- "Shikigami.PackageArchitectureSpec" does.
repositoryRoot :: IO FilePath
repositoryRoot = go [".", ".."]
  where
    go [] = assertFailure "cannot find cabal.project from the working directory; tried \".\" and \"..\""
    go (candidate : rest) = do
      exists <- doesFileExist (candidate </> "cabal.project")
      if exists then pure candidate else go rest
