import unittest

from check_haskell import BANNER, BASELINE, check_cabal, check_source, mask_haskell


class HaskellConventions(unittest.TestCase):
    def rules(self, source, path="shikigami-core/src/Example.hs"):
        return [line.split(": ")[1] for line in check_source(path, source)]

    def test_real_regressions_are_rejected(self):
        fixtures = {
            "postpositive-qualified": "import qualified Data.Text as Text",
            "explicit-deriving": "data Example = Example deriving (Eq, Show)",
            "unqualified-operator": "value = Aeson.object [\"key\" Aeson..= x]",
            "strict-field": "data Example = Example {status :: Text}",
            "unprefixed-field": "data Example = Example {exampleStatus :: !Text}",
            "package-import-boundary": 'import "text" Data.Text (Text)',
        }
        for rule, fixture in fixtures.items():
            with self.subTest(rule=rule):
                self.assertIn(rule, self.rules("module Example where\n" + fixture))

    def test_literals_nested_comments_and_promotions_are_not_code_findings(self):
        source = '''module Example where
{- outer {- import qualified Wrong -}
data Example = Example {exampleStatus :: Text}
-}
value = "import qualified Wrong; deriving (Eq); Aeson..="
multiline = """
  data Example = Example {exampleStatus :: Text}
  """
quoted = [sql|SELECT 'Aeson..='|]
character = 'x'
route = Proxy @'GET
data Good = Good {status :: !Text} deriving stock (Eq)
'''
        self.assertEqual([], self.rules(source))
        masked = mask_haskell(source)
        self.assertEqual(len(source), len(masked))
        self.assertEqual(source.count("\n"), masked.count("\n"))
        self.assertIn("@'GET", masked)

    def test_newtypes_entity_ids_and_servant_route_declarations(self):
        source = '''module Example where
newtype Identifier = Identifier {value :: Text} deriving stock (Eq)
data Run = Run {runId :: !Identifier} deriving stock (Eq)
data Routes mode = Routes {read :: mode :- Get '[JSON] Value}
'''
        self.assertEqual([], self.rules(source))

    def test_type_signatures_after_a_record_are_not_fields(self):
        self.assertEqual([], self.rules('''module Example where
data Good = Good {value :: !Text}
first, second :: Int
first = 1
second = 2
'''))

    def test_multiline_fields_and_sum_alternatives(self):
        source = '''module Example where
data Good
  = A {value :: !Text}
  | B {count :: Int}
  deriving stock (Eq)
'''
        self.assertEqual(["strict-field"], self.rules(source))

    def test_generated_ownership_is_narrow_and_versioned(self):
        path = "shikigami-core/src/Example/Generated/Domain.hs"
        self.assertEqual([], self.rules(BANNER + "\nmodule Example.Generated.Domain where", path))
        released = "-- @generated by keiro-dsl 0.22.0.0 (language keiro-dsl 6) from aggregate Example; do not edit."
        self.assertEqual([], self.rules(released, path))
        self.assertIn("generated-firewall", self.rules("module Example.Generated.Domain where", path))
        self.assertIn("explicit-deriving", self.rules(BANNER + "\ndata Example = Example deriving (Eq)"))
        self.assertIn("generated-firewall", self.rules(released.replace("0.22.0.0", "9.0.0.0"), path))

    def test_prelude_keeps_orphan_out_and_pins_package_imports(self):
        path = "shikigami-core/src/Shikigami/Prelude.hs"
        self.assertEqual([], self.rules('module Shikigami.Prelude where\nimport "text" Data.Text', path))
        self.assertIn("prelude-orphan", self.rules('module Shikigami.Prelude where\nimport Data.Generics.Labels ()', path))

    def test_every_package_component_inherits_the_baseline(self):
        source = "common common\n  default-language: GHC2024\n  default-extensions:\n"
        source += "".join("    " + extension + "\n" for extension in sorted(BASELINE))
        source += "\n  ghc-options: -Wall -Werror=missing-fields\n\nlibrary\n  import: common\n\ntest-suite sample\n  import: common\n"
        self.assertEqual([], check_cabal("example.cabal", source))
        for original, changed in [
            ("GHC2024", "GHC2021"),
            ("    DuplicateRecordFields\n", ""),
            ("-Werror=missing-fields", ""),
            ("test-suite sample\n  import: common", "test-suite sample\n  hs-source-dirs: test"),
        ]:
            with self.subTest(mutation=original):
                self.assertTrue(check_cabal("example.cabal", source.replace(original, changed)))


if __name__ == "__main__":
    unittest.main()
