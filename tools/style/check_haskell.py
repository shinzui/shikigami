#!/usr/bin/env python3
"""Check stable hand-owned Haskell invariants, without rewriting generated code.

This lexical check complements compilation and behavioral tests. It cannot prove
domain modeling, authority, JSON compatibility or cancellation semantics.
"""

import argparse
from pathlib import Path
import re
import subprocess

BASELINE = {
    "DeriveAnyClass", "DuplicateRecordFields", "OverloadedLabels",
    "OverloadedStrings", "NoFieldSelectors", "OverloadedRecordDot",
}
BANNER = "-- @generated by keiro-dsl; do not edit. Regenerated from the .keiro spec."


def mask_haskell(source):
    """Preserve code offsets/newlines; hide nested comments and literal bodies."""
    result = list(source)
    i = 0

    def hide(start, end):
        for position in range(start, end):
            if result[position] != "\n":
                result[position] = " "

    while i < len(source):
        start = i
        if source.startswith("--", i):
            end = source.find("\n", i)
            i = len(source) if end < 0 else end
        elif source.startswith("{-", i):
            depth = 1
            i += 2
            while i < len(source) and depth:
                if source.startswith("{-", i):
                    depth += 1
                    i += 2
                elif source.startswith("-}", i):
                    depth -= 1
                    i += 2
                else:
                    i += 1
        elif source[i] == '"':
            delimiter = '"""' if source.startswith('"""', i) else '"'
            i += len(delimiter)
            while i < len(source):
                if source[i] == "\\":
                    i += 2
                elif source.startswith(delimiter, i):
                    i += len(delimiter)
                    break
                else:
                    i += 1
            i = min(i, len(source))
        elif source[i] == "'" and (character := re.match(r"'(?:[^'\\\n]|\\[^\n]{1,8})'", source[i:])):
            i += len(character.group())
        elif quasiquote := re.match(r"\[[a-zA-Z][\w.]*\|", source[i:]):
            end = source.find("|]", i + len(quasiquote.group()))
            i = len(source) if end < 0 else end + 2
        else:
            i += 1
            continue
        hide(start, i)
    return "".join(result)


def check_source(path, source):
    findings = []

    def report(offset, rule, message):
        findings.append(f"{path}:{source.count(chr(10), 0, offset) + 1}: {rule}: {message}")

    if "Generated" in Path(path).parts:
        if BANNER not in source and not re.search(r"(?m)^-- @generated by keiro-dsl 0\.22\.0\.0 .*; do not edit\.$", source):
            report(0, "generated-firewall", "generated path lacks the exact owner banner")
        return findings
    if "keiro-dsl-conformance.workspace.shikigami" in Path(path).parts:
        return findings  # The generated tooling package is checked by keiro-gate.

    code = mask_haskell(source)
    for pattern, rule, message in [
        (r"(?m)^\s*import\s+qualified\b", "postpositive-qualified", "put qualified after the module name"),
        (r"\bderiving\b(?!\s+(?:stock|newtype|anyclass|via)\b)", "explicit-deriving", "name the deriving strategy"),
        (r"\b[A-Z]\w*\.([!#$%&*+./<=>?@\\^|~:-]+)", "unqualified-operator", "import the operator unqualified"),
    ]:
        for match in re.finditer(pattern, code):
            report(match.start(), rule, message)

    module = re.search(r"\bmodule\s+([\w.]+)", code)
    module_name = module.group(1) if module else ""
    uses_record_lens = re.search(r"#[a-zA-Z]\w*\s*(?:\.~|%~|\?~)|\^\.\s*#[a-zA-Z]", code)
    if uses_record_lens and not re.search(r"(?m)^import\s+Data\.Generics\.Labels\s*\(\s*\)", code):
        report(uses_record_lens.start(), "local-label-orphan", "import Data.Generics.Labels () in the module using record lenses")
    if module_name.endswith(".Prelude"):
        if re.search(r"(?m)^import\s+(?:\"[^\"]+\"\s+)?Data\.Generics\.Labels\b", code):
            report(0, "prelude-orphan", "the generic-lens orphan must not propagate through Prelude")
    else:
        for match in re.finditer(r"(?m)^\s*import\s+", code):
            if re.match(r'\s*import\s+"', source[match.start():]):
                report(match.start(), "package-import-boundary", "package-qualified imports belong only in Prelude")

    declarations = list(re.finditer(r"(?m)^(data|newtype)\s+([A-Z]\w*)\b", code))
    for index, declaration in enumerate(declarations):
        end = declarations[index + 1].start() if index + 1 < len(declarations) else len(code)
        block = code[declaration.end():end]
        next_top_level = re.search(r"\n(?=\S)", block)
        if next_top_level:
            block = block[:next_top_level.start()]
        stems = [declaration.group(2), module_name.rsplit(".", 1)[-1]]
        for field in re.finditer(r"[{,]\s*([a-z_]\w*)\s*::\s*([^\n,}]+)", block):
            name, field_type = field.groups()
            offset = declaration.end() + field.start()
            # ID labels name the identity itself (runId, executionId), not a
            # selector-disambiguation prefix. Newtype fields cannot be strict.
            prefixed = any(re.match(re.escape(stem[:1].lower() + stem[1:]) + r"[A-Z]", name) for stem in stems if stem)
            if name.startswith("_") or (prefixed and not name.endswith("Id")):
                report(offset, "unprefixed-field", f"use a direct field name instead of {name}")
            # Servant mode :- route fields are generic type-level declarations,
            # whose upstream contract specifies the laziness of their fields.
            if declaration.group(1) != "newtype" and not field_type.startswith("!") and ":-" not in field_type:
                report(offset, "strict-field", f"make {name} strict")
    return findings


def check_cabal(path, source):
    findings = []
    common = re.search(r"(?ms)^common common\s*\n(.*?)(?=^\S|\Z)", source)
    if not common or not re.search(r"default-language:\s*GHC2024\b", common.group(1)):
        return [f"{path}:1: cabal-baseline: declare common common with GHC2024"]
    body = common.group(1)
    extensions = re.search(r"(?ms)^  default-extensions:\s*\n(.*?)(?=^  \S|\Z)", body)
    enabled = set(re.findall(r"\w+", extensions.group(1))) if extensions else set()
    for extension in sorted(BASELINE - enabled):
        findings.append(f"{path}:1: cabal-baseline: missing {extension}")
    if "PackageImports" in enabled:
        findings.append(f"{path}:1: package-import-boundary: enable PackageImports only in Prelude")
    if "-Werror=missing-fields" not in body:
        findings.append(f"{path}:1: complete-record-construction: missing fields must fail compilation")
    for component in re.finditer(r"(?ms)^(?:library|executable|test-suite|benchmark)\b[^\n]*\n(.*?)(?=^\S|\Z)", source):
        if not re.search(r"^  import:\s*common\s*$", component.group(1), re.M):
            findings.append(f"{path}:1: cabal-baseline: every component must import common")
    return findings


def check_repository(root):
    listed = subprocess.check_output(
        ["git", "ls-files", "--cached", "--others", "--exclude-standard"], cwd=root, text=True,
    ).splitlines()
    findings = []
    for name in sorted(set(listed)):
        path = root / name
        if not path.is_file() or not name.startswith("shikigami-"):
            continue
        if path.suffix == ".hs":
            findings.extend(check_source(name, path.read_text()))
        elif path.suffix == ".cabal" and len(Path(name).parts) == 2:
            findings.extend(check_cabal(name, path.read_text()))
    return findings


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[2])
    args = parser.parse_args()
    findings = check_repository(args.root)
    print("\n".join(findings) if findings else "Haskell conventions: passed (hand-owned source and seven package baselines).")
    return bool(findings)


if __name__ == "__main__":
    raise SystemExit(main())
